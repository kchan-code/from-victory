-- 2. private.apple_signin_handoffs
-- ---------------------------------------------------------------------------
create table private.apple_signin_handoffs (
  -- >= 128 bits of entropy (22+ base64url chars), generated by the app.
  id              text        primary key check (length(id) >= 22),
  state           text        not null default 'pending'
                              check (state in ('pending', 'claimed', 'burned')),
  challenge       text        not null,   -- SHA256(verifier), base64url
  oauth_state     text        not null,   -- the OAuth `state` param (bind/audit)
  client_id       text        not null,
  sub             text        not null,
  -- Packed "iv.tag.ciphertext" (base64url), AAD = "handoff|<id>".
  id_token_enc    text        not null,
  nonce_enc       text        not null,
  refresh_enc     text        not null,
  key_version     integer     not null check (key_version >= 1),
  attempts        integer     not null default 0 check (attempts between 0 and 5),
  claim_id        uuid,
  claimed_at      timestamptz,
  expires_at      timestamptz not null,
  -- Purge bookkeeping: failed revoke attempts before the row is force-deleted.
  revoke_attempts integer     not null default 0 check (revoke_attempts >= 0),
  created_at      timestamptz not null default now()
);

create index apple_signin_handoffs_expires_idx
  on private.apple_signin_handoffs (expires_at);

