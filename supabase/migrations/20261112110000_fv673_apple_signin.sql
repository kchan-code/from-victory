-- 3a. Create a handoff row (Android callback).
create or replace function public.create_apple_handoff(
  p_id            text,
  p_challenge     text,
  p_oauth_state   text,
  p_client_id     text,
  p_sub           text,
  p_id_token_enc  text,
  p_nonce_enc     text,
  p_refresh_enc   text,
  p_key_version   integer,
  p_expires_at    timestamptz
) returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into private.apple_signin_handoffs
    (id, challenge, oauth_state, client_id, sub, id_token_enc, nonce_enc,
     refresh_enc, key_version, expires_at)
  values
    (p_id, p_challenge, p_oauth_state, p_client_id, p_sub, p_id_token_enc,
