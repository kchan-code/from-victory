-- Purpose (FV-673, SSO A4 — Apple sign-in server core; spec FV-569 §5.4/§5.5):
--
--   1. private.apple_signin_tokens   — the ONE stored Apple credential per
--      (user, client): an AES-256-GCM encrypted refresh token, kept solely so
--      we can call Apple's /auth/revoke before any account deletion.
--   2. private.apple_signin_handoffs — short-lived (3 min) row that carries the
--      verified Apple credentials from the Android Auth Tab callback into the
--      WebView, where the session is created (bound by a verifier challenge).
--   3. Service-role-only functions in public (PostgREST rpc) that are the ONLY
--      path to those tables: claim (atomic, fenced), verifier-mismatch,
--      release-claim, finalize (one-transaction transfer), upsert, list,
--      delete, and the purge helpers.
--
-- Privacy model:
--   - Both tables live in schema `private` (not exposed to PostgREST; USAGE
--     revoked from client roles), have RLS ENABLED with NO policies, and have
--     every table privilege revoked from public/anon/authenticated. Even a
--     misconfigured exposure would return zero rows.
--   - No new athlete PII. The stored values are opaque Apple identifiers
--     (sub, client_id) and ciphertext; the app never stores email/name/photo.
--   - Cascading delete: apple_signin_tokens.user_id references auth.users
--     ON DELETE CASCADE, so account deletion removes the credential row.
--     Handoff rows have no user (none exists yet) and are purged by expiry.
--   - Functions are SECURITY DEFINER, search_path = '', EXECUTE granted to
--     service_role ONLY (revoked from public/anon/authenticated explicitly).
--
-- Not in this migration: the §5.2 pending-account functions and the
-- apple_signin / apple_handoff rate-limit buckets (FV-671,
-- 20261112100000_fv671_pending_accounts.sql).
