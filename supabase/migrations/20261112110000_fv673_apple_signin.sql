-- 3h. Delete one token row (after a successful revoke where the user survives).
create or replace function public.delete_apple_signin_token(
  p_user_id uuid,
  p_client_id text
) returns void
language sql
security definer
set search_path = ''
as $$
  delete from private.apple_signin_tokens as t
   where t.user_id = p_user_id and t.client_id = p_client_id;
$$;

-- 3i. Purge candidates: expired or burned rows (stale-claimed rows are
--     reclaimable until they expire, so they are purged only once expired).
create or replace function public.list_apple_handoffs_for_purge(p_limit integer)
returns table (
  id              text,
  client_id       text,
  refresh_enc     text,
  key_version     integer,
  revoke_attempts integer
)
language sql
security definer
set search_path = ''
as $$
  select h.id, h.client_id, h.refresh_enc, h.key_version, h.revoke_attempts
    from private.apple_signin_handoffs as h
   where h.expires_at <= now() or h.state = 'burned'
   order by h.created_at
   limit greatest(1, least(coalesce(p_limit, 20), 100));
$$;

-- 3j. Bump the failed-revoke counter; returns the new count (null if gone).
create or replace function public.record_apple_handoff_revoke_attempt(p_id text)
returns integer
language sql
security definer
set search_path = ''
as $$
  update private.apple_signin_handoffs as h
     set revoke_attempts = h.revoke_attempts + 1
   where h.id = p_id
  returning h.revoke_attempts;
$$;

-- 3k. Delete a purgeable row (same predicate as the listing, so a row that was
--     meanwhile reset is never deleted).
create or replace function public.delete_apple_handoff_purged(p_id text)
returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  n integer;
begin
  delete from private.apple_signin_handoffs as h
   where h.id = p_id and (h.expires_at <= now() or h.state = 'burned');
  get diagnostics n = row_count;
  return n > 0;
end;
$$;

