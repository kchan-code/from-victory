-- 3b. Atomic claim with a fencing token. A row claimed more than 2 minutes ago
--     is treated as interrupted: it is re-claimed with a NEW claim_id (which
--     fences out the slow original request). Burned/expired rows never match.
create or replace function public.claim_apple_handoff(p_id text)
returns table (
  claim_id     uuid,
  challenge    text,
  client_id    text,
  sub          text,
  id_token_enc text,
  nonce_enc    text,
  refresh_enc  text,
  key_version  integer
)
language sql
security definer
set search_path = ''
as $$
  update private.apple_signin_handoffs as h
     set state = 'claimed',
         claim_id = gen_random_uuid(),
         claimed_at = now()
   where h.id = p_id
     and h.expires_at > now()
     and (
       h.state = 'pending'
       or (h.state = 'claimed' and h.claimed_at < now() - interval '2 minutes')
     )
  returning h.claim_id, h.challenge, h.client_id, h.sub, h.id_token_enc,
            h.nonce_enc, h.refresh_enc, h.key_version;
$$;

-- 3c. Verifier mismatch: attempts + 1, back to pending (burned at 5), guarded
--     by claim_id. Returns the new state, or null if the fence failed.
create or replace function public.record_apple_handoff_mismatch(
  p_id text,
  p_claim_id uuid
) returns text
language sql
security definer
set search_path = ''
as $$
  update private.apple_signin_handoffs as h
     set attempts = h.attempts + 1,
         state = case when h.attempts + 1 >= 5 then 'burned' else 'pending' end,
         claim_id = null,
         claimed_at = null
   where h.id = p_id
     and h.claim_id = p_claim_id
     and h.state = 'claimed'
  returning h.state;
$$;

-- 3d. Release a claim (transient failure): back to pending, credentials kept,
--     attempts untouched. Guarded by claim_id.
create or replace function public.release_apple_handoff(
  p_id text,
  p_claim_id uuid
) returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  n integer;
begin
  update private.apple_signin_handoffs as h
     set state = 'pending', claim_id = null, claimed_at = null
   where h.id = p_id and h.claim_id = p_claim_id and h.state = 'claimed';
  get diagnostics n = row_count;
  return n > 0;
end;
$$;

-- 3e. Token upsert (every Apple redemption issues a new refresh token; the
--     replaced token is intentionally NOT revoked — spec §5.5).
create or replace function public.upsert_apple_signin_token(
  p_user_id     uuid,
  p_client_id   text,
  p_sub         text,
  p_ciphertext  text,
  p_iv          text,
  p_tag         text,
  p_key_version integer
) returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into private.apple_signin_tokens as t
    (user_id, client_id, sub, ciphertext, iv, tag, key_version)
  values
    (p_user_id, p_client_id, p_sub, p_ciphertext, p_iv, p_tag, p_key_version)
  on conflict (user_id, client_id) do update
    set sub = excluded.sub,
        ciphertext = excluded.ciphertext,
        iv = excluded.iv,
        tag = excluded.tag,
        key_version = excluded.key_version,
        created_at = now();
end;
$$;

-- 3f. Finalize: ONE transaction. Delete the handoff only if this caller still
--     holds the claim (fence), then upsert the token under the row's own
--     client_id/sub. Returns false (and changes nothing) if the fence failed.
create or replace function public.finalize_apple_handoff(
  p_handoff_id  text,
  p_claim_id    uuid,
  p_user_id     uuid,
  p_ciphertext  text,
  p_iv          text,
  p_tag         text,
  p_key_version integer
) returns boolean
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_client_id text;
  v_sub text;
begin
  delete from private.apple_signin_handoffs as h
   where h.id = p_handoff_id and h.claim_id = p_claim_id and h.state = 'claimed'
  returning h.client_id, h.sub into v_client_id, v_sub;

  if not found then
    return false;
  end if;

  insert into private.apple_signin_tokens as t
    (user_id, client_id, sub, ciphertext, iv, tag, key_version)
  values
    (p_user_id, v_client_id, v_sub, p_ciphertext, p_iv, p_tag, p_key_version)
  on conflict (user_id, client_id) do update
    set sub = excluded.sub,
        ciphertext = excluded.ciphertext,
        iv = excluded.iv,
        tag = excluded.tag,
        key_version = excluded.key_version,
        created_at = now();

  return true;
end;
$$;

-- 3g. Read tokens for revoke.
